"""Rules shared by every creative agent. Added after the first real run invented facts about real people."""

REAL_WORLD_RULES = """REAL-WORLD RULES (always apply):
- Real people, religions, living organisations and real events: use only facts stated in the dossier. Never invent their words, beliefs, motives, conflicts, crimes or private moments.
- To dramatise, use FICTIONAL characters inside a real setting. Real figures may appear as narrated, sourced facts or as silent background, never as invented dialogue.
- Never place a person, group or organisation in a time before it existed. Keep every date consistent with the dossier.
- Never connect two real subjects (for example a historical figure and a modern organisation) unless the dossier states the connection.
- Never allege crimes or wrongdoing against any real person or organisation."""
